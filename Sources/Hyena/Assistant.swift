/// Hyena's on-device assistant. Uses Apple's Foundation Models when Apple
/// Intelligence is available; otherwise every feature falls back to
/// deterministic answers. Nothing leaves the Mac, and the model never
/// selects or deletes anything by itself.
enum Assistant {
    enum Status: Equatable {
        case ready
        case unavailable(String)

        var isReady: Bool { self == .ready }
    }

    static var status: Status {
        #if canImport(FoundationModels)
        if #available(macOS 26.0, *) {
            switch SystemLanguageModel.default.availability {
            case .available: return .ready
            case .unavailable(.deviceNotEligible): return .unavailable("This Mac doesn’t support Apple Intelligence.")
            case .unavailable(.appleIntelligenceNotEnabled):
                return .unavailable("Turn on Apple Intelligence in System Settings to enable the on-device model.")
            case .unavailable(.modelNotReady): return .unavailable("The on-device model is still downloading.")
            case .unavailable: return .unavailable("The on-device model isn’t available right now.")
            }
        }
        #endif
        return .unavailable("Requires macOS 26 with Apple Intelligence.")
    }

    struct Explanation: Equatable, Sendable {
        var summary: String
        var owner: String
        var advice: String
        var verdict: Verdict

        enum Verdict: String, Sendable { case safe, caution, keep }
    }

    // MARK: Explain

    static func explain(_ facts: ItemFacts) async throws -> Explanation {
        #if canImport(FoundationModels)
        if #available(macOS 26.0, *), status.isReady {
            let session = LanguageModelSession(instructions: """
                You are Hyena, a careful Mac storage assistant for developers. Explain what a folder or file is, \
                which app or tool creates it, and whether removing it is safe. Use only the facts provided plus \
                well-known conventions of macOS and developer tools. If you are not sure, say so plainly. \
                Never claim something is safe when it may hold user data. Keep each field to one or two short sentences.
                """)
            let response = try await session.respond(
                to: "Explain this item found on the user's Mac:\n\(facts.promptDescription)",
                generating: ExplanationDraft.self,
                options: GenerationOptions(temperature: 0.2)
            )
            let draft = response.content
            return Explanation(
                summary: draft.summary, owner: draft.owner, advice: draft.advice,
                verdict: Explanation.Verdict(rawValue: draft.verdict.rawValue) ?? .caution
            )
        }
        #endif
        return fallbackExplanation(facts)
    }

    static func fallbackExplanation(_ facts: ItemFacts) -> Explanation {
        let verdict: Explanation.Verdict = facts.category == .appLeftovers ? .keep
            : facts.recommended ? .safe : .caution
        return Explanation(
            summary: facts.kind.map { "\($0.title) generated by your project’s tooling." } ?? facts.category.summary,
            owner: facts.owningApp ?? facts.kind?.shortTitle ?? "Unknown",
            advice: facts.whatHappens,
            verdict: verdict
        )
    }

    // MARK: Digest

    /// A short, friendly paragraph built from deterministic insights.
    static func digest(_ insights: [Insight], selectedBytes: Int64) async -> String? {
        guard !insights.isEmpty else { return nil }
        #if canImport(FoundationModels)
        if #available(macOS 26.0, *), status.isReady {
            let facts = insights.map { "- " + $0.text }.joined(separator: "\n")
            let session = LanguageModelSession(instructions: """
                You write a two-sentence storage digest for a developer's Mac, reporting what a scan found. \
                Nothing has been cleaned or deleted: describe space that could be freed if the user chooses to, \
                and never say anything is being or was cleaned. Be specific, calm and brief. Use only the facts \
                given, keep every number exactly as written, and do not invent anything. No bullet points, \
                no greetings, no "we".
                """)
            if let response = try? await session.respond(
                to: "Scan findings:\n\(facts)\nSpace the user could free with the current selection: \(space(selectedBytes)).",
                options: GenerationOptions(temperature: 0.4)
            ) {
                return response.content.trimmingCharacters(in: .whitespacesAndNewlines)
            }
        }
        #endif
        return insights.prefix(2).map(\.text).joined(separator: " ")
    }

    // MARK: Suggestions

    /// Lets the on-device model pick and phrase the most relevant suggestions
    /// for this user. Falls back to the deterministic order.
    static func personalize(_ suggestions: [Suggestion], profile: String, limit: Int = 3) async -> (items: [Suggestion], usedModel: Bool) {
        let fallback = Array(suggestions.prefix(limit))
        guard suggestions.count > 1 else { return (fallback, false) }
        #if canImport(FoundationModels)
        if #available(macOS 26.0, *), status.isReady {
            let list = suggestions.enumerated().map { index, item in
                "\(index): [\(item.kind.title)] \(item.title). \(item.detail) (\(space(item.bytes)))"
            }.joined(separator: "\n")
            let session = LanguageModelSession(instructions: """
                You help a developer keep their Mac tidy. From numbered cleanup suggestions, choose the ones \
                this user is most likely to want, considering their habits. Always keep a low-disk warning if \
                present. For each pick, write one short, friendly sentence (max 18 words) saying why it's worth \
                doing now. Use only facts given; keep numbers exactly as written. Nothing has been cleaned yet. \
                Never claim cleaning makes the Mac faster or improves performance; it only frees space.
                """)
            if let response = try? await session.respond(
                to: "User profile:\n\(profile)\n\nSuggestions:\n\(list)\n\nPick up to \(limit).",
                generating: SuggestionPicks.self, options: GenerationOptions(temperature: 0.3)
            ) {
                var seen = Set<Int>()
                var picked: [Suggestion] = []
                for pick in response.content.picks where suggestions.indices.contains(pick.index) {
                    guard seen.insert(pick.index).inserted else { continue }
                    var item = suggestions[pick.index]
                    let reason = pick.reason.trimmingCharacters(in: .whitespacesAndNewlines)
                    if !reason.isEmpty && reason.count < 160 { item.detail = reason }
                    picked.append(item)
                }
                // A low-disk warning is never dropped by the model.
                if let urgent = suggestions.first(where: { $0.kind == .lowDisk }), !picked.contains(where: { $0.id == urgent.id }) {
                    picked.insert(urgent, at: 0)
                }
                if !picked.isEmpty { return (Array(picked.prefix(limit)), true) }
            }
        }
        #endif
        return (fallback, false)
    }

    // MARK: Ask Hyena

    struct Interpretation: Sendable {
        var rule: SelectionRule
        var usedModel: Bool
    }

    /// Turns a request like "clean old Rust builds except work" into a rule
    /// the user reviews before anything is selected.
    static func interpret(_ request: String) async -> Interpretation {
        let parsed = RuleParser.parse(request)
        #if canImport(FoundationModels)
        if #available(macOS 26.0, *), status.isReady {
            let categories = CleanupCategory.allCases.map { "\($0.rawValue) (\($0.title))" }.joined(separator: ", ")
            let kinds = ArtifactKind.allCases.map { "\($0.rawValue) (\($0.title))" }.joined(separator: ", ")
            let session = LanguageModelSession(instructions: """
                You convert a developer's cleanup request into a selection rule for Hyena, a Mac cleaner. \
                Category ids: \(categories). \
                Project kind ids (only for project builds): \(kinds). \
                Leave lists empty when the request doesn't restrict them. Exclusion keywords are words that \
                identify folders or projects to keep (for example "work" from "except my work projects"). \
                Express ages in days (a month is 30). Use 0 when there is no age or size limit.
                """)
            if let response = try? await session.respond(
                to: request, generating: RuleDraft.self, options: GenerationOptions(temperature: 0)
            ) {
                let draft = response.content
                var rule = SelectionRule(
                    categories: Set(draft.categories.compactMap(CleanupCategory.init(rawValue:))),
                    kinds: Set(draft.kinds.compactMap(ArtifactKind.init(rawValue:))),
                    olderThanDays: draft.olderThanDays > 0 ? draft.olderThanDays : nil,
                    largerThanBytes: draft.minimumMegabytes > 0 ? Int64(draft.minimumMegabytes) * 1_000_000 : nil,
                    excludeKeywords: draft.excludeKeywords.map { $0.lowercased() }.filter { !$0.isEmpty },
                    includeKeywords: draft.includeKeywords.map { $0.lowercased() }.filter { !$0.isEmpty },
                    includeReviewItems: draft.includeItemsMarkedForReview
                )
                // Small models over-select categories. Explicit wording the parser
                // understood wins; a request about project kinds stays in projects.
                if !parsed.categories.isEmpty {
                    rule.categories = parsed.categories
                } else if !rule.kinds.isEmpty {
                    rule.categories = [.projects]
                }
                if !parsed.kinds.isEmpty { rule.kinds = parsed.kinds }
                // Listing most kinds means the model saw no real restriction.
                if rule.kinds.count > 4 { rule.kinds = [] }
                // Keywords must come from the request itself, never be invented.
                let lowered = request.lowercased()
                rule.excludeKeywords = rule.excludeKeywords.filter { lowered.contains($0) }
                rule.includeKeywords = parsed.includeKeywords.filter { !rule.excludeKeywords.contains($0) }
                if !rule.kinds.isEmpty && rule.categories.isEmpty { rule.categories = [.projects] }
                if parsed.includeReviewItems == false { rule.includeReviewItems = false }
                if parsed.olderThanDays != nil { rule.olderThanDays = parsed.olderThanDays }
                if parsed.largerThanBytes != nil { rule.largerThanBytes = parsed.largerThanBytes }
                if !parsed.excludeKeywords.isEmpty {
                    rule.excludeKeywords = Array(Set(rule.excludeKeywords + parsed.excludeKeywords)).sorted()
                }
                return Interpretation(rule: rule, usedModel: true)
            }
        }
        #endif
        return Interpretation(rule: parsed, usedModel: false)
    }
}

#if canImport(FoundationModels)
@available(macOS 26.0, *)
@Generable
struct ExplanationDraft {
    @Guide(description: "What this item is, in plain language.")
    var summary: String
    @Guide(description: "The app or developer tool that creates it, or Unknown.")
    var owner: String
    @Guide(description: "What happens if it is removed, and what to do first if anything.")
    var advice: String
    @Guide(description: "safe: regenerates automatically. caution: check first. keep: likely holds data the user needs.")
    var verdict: VerdictDraft

    @Generable
    enum VerdictDraft: String {
        case safe, caution, keep
    }
}

@available(macOS 26.0, *)
@Generable
struct RuleDraft {
    @Guide(description: "Category ids to include. Empty means all categories.")
    var categories: [String]
    @Guide(description: "Project kind ids to include. Empty means all kinds.")
    var kinds: [String]
    @Guide(description: "Only items not modified for at least this many days. 0 means no limit.")
    var olderThanDays: Int
    @Guide(description: "Only items at least this many megabytes. 0 means no limit.")
    var minimumMegabytes: Int
    @Guide(description: "Lowercase keywords for folders or projects to keep.")
    var excludeKeywords: [String]
    @Guide(description: "Lowercase keywords that items must contain, only if the request limits to specific folders.")
    var includeKeywords: [String]
    @Guide(description: "True only if the user explicitly wants risky or review items included.")
    var includeItemsMarkedForReview: Bool
}

@available(macOS 26.0, *)
@Generable
struct SuggestionPicks {
    @Guide(description: "Chosen suggestions, most useful first.", .maximumCount(3))
    var picks: [Pick]

    @Generable
    struct Pick {
        @Guide(description: "The number of the chosen suggestion.")
        var index: Int
        @Guide(description: "One short sentence on why it's worth doing now.")
        var reason: String
    }
}
#endif
